#!/usr/bin/env bash
# autorestore_install_v9.sh — unit v9 = v8 + (1) per-port PIPELINING: each port's cuda-checkpoint restore starts as soon as its own
# criu restore returns (v8 waited for all four); (2) image set selectable (IMG_PREFIX, default /mnt/fs/snap-); (3) job-file reseed
# target read from <image>/.jobpath (fallback ~/jobs/current-<port>); (4) SLEEP-MODE images (<image>/.sleeping): the model is
# prewarmed (16-way cat) concurrently with the CRIU leg, and after unlock each port gets POST /wake_up + /collective_rpc
# reload_weights before the health gate; (5) fabric-manager wait (nvidia-smi Fabric State == Completed) before any GPU restore —
# small images restore in seconds, before FM finishes on a fresh boot; (6) threads per restore PMT (lever-1 sweep result).
# Env at install: PORTS, PMT, CRIU_BIN, RESTORE_ARGS, IMG_PREFIX, MODEL, UNIT_SCRIPT (default /usr/local/bin/criu-autorestore.sh).
# Installing with UNIT_SCRIPT=/usr/local/bin/criu-autorestore-v9.sh INSTALL_UNIT=0 writes the script only (manual same-boot runs).
set -uo pipefail
PORTS=${PORTS:-"8201 8202 8203 8204"}; PMT=${PMT:-12}; CRIU_BIN=${CRIU_BIN:-/usr/local/bin/criu-hp2}
RESTORE_ARGS=${RESTORE_ARGS:-"--premap-threads $PMT --premap-hugepage"}; IMG_PREFIX=${IMG_PREFIX:-/mnt/fs/snap-}
MODEL=${MODEL:-/mnt/fs/glm52-nvfp4}; UNIT_SCRIPT=${UNIT_SCRIPT:-/usr/local/bin/criu-autorestore.sh}; INSTALL_UNIT=${INSTALL_UNIT:-1}
LOGF=${LOGF:-/var/log/criu-autorestore.log}
sudo tee "$UNIT_SCRIPT" >/dev/null <<SCRIPT
#!/usr/bin/env bash
# criu-autorestore v9 (generated by autorestore_install_v9.sh)
set -uo pipefail
exec > $LOGF 2>&1
echo "start \$(date -u +%T) v9 images=$IMG_PREFIX pmt=$PMT"
echo 200000 | tee /proc/sys/kernel/ns_last_pid >/dev/null
export PATH=/home/spinup/venv/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin
T0=\$(date +%s)
PORTS="$PORTS"; IMG=$IMG_PREFIX; MODEL=$MODEL
el(){ echo "+\$(( \$(date +%s) - T0 ))s"; }
mkdir -p /mnt/fs; mountpoint -q /mnt/fs || mount -t virtiofs sharedfs /mnt/fs; mountpoint -q /mnt/fs || { echo NO_FS; exit 1; }
for P in \$PORTS; do iptables -I INPUT -p tcp --dport \$P ! -i lo -j DROP; done; echo "ports gated \$(el)"
SLEEPY=0
for P in \$PORTS; do
  DIR=\$IMG\$P; [ -d "\$DIR" ] || { echo "missing \$DIR"; continue; }
  J=\$(cat "\$DIR/.jobpath" 2>/dev/null || cat /home/spinup/jobs/current-\$P 2>/dev/null)
  [ -n "\$J" ] && [ -f "\$DIR/.jobfile" ] && cp "\$DIR/.jobfile" "\$J" && chown spinup:spinup "\$J" && echo "\$P: job file reseeded -> \$J (\$(md5sum "\$J" | cut -c1-8))"
  [ -f "\$DIR/.logsize" ] && truncate -s "\$(cat "\$DIR/.logsize")" /home/spinup/glm-\$P.log && chown spinup:spinup /home/spinup/glm-\$P.log
  [ -f "\$DIR/.sleeping" ] && SLEEPY=1
done
rm -f /dev/shm/*.cr_link 2>/dev/null
CUR=\$(hostname -I | awk '{print \$1}')
for P in \$PORTS; do DIR=\$IMG\$P; [ -f "\$DIR/.hostip" ] || continue; OLDIP=\$(cat "\$DIR/.hostip"); [ -n "\$OLDIP" ] && [ "\$OLDIP" != "\$CUR" ] && ip addr add "\$OLDIP/32" dev lo 2>/dev/null && echo "aliased \$OLDIP"; done
# sleep-mode images: the weights are not in the image; prewarm the model into the page cache concurrently with the CRIU leg
rm -f /run/criu-prewarm.done
if [ "\$SLEEPY" = 1 ]; then ( TP=\$(date +%s); ls \$MODEL/* | xargs -P 16 -n 1 cat > /dev/null; echo "prewarm done \$(el) (\$(( \$(date +%s) - TP ))s)"; touch /run/criu-prewarm.done ) & else touch /run/criu-prewarm.done; fi
gpu_node(){ local B; B=\$(nvidia-smi --query-gpu=pci.bus_id --format=csv,noheader -i "\$1" 2>/dev/null | sed 's/^0000//' | tr 'A-F' 'a-f'); cat /sys/bus/pci/devices/\$B/numa_node 2>/dev/null; }
fabric_wait(){ rm -f /run/criu-fabric.done; for i in \$(seq 1 120); do n=\$(nvidia-smi -q 2>/dev/null | grep -A3 -i "^ *Fabric" | grep -ci "State *: *Completed"); [ "\$n" -ge 8 ] && { echo "fabric completed on \$n GPUs \$(el)"; break; }; sleep 1; done; [ -f /run/criu-fabric.done ] || [ "\$n" -ge 8 ] || echo "fabric NOT completed after 120 s (n=\$n) \$(el)"; touch /run/criu-fabric.done; }
CKPT=/usr/local/bin/cuda-checkpoint
restore_one(){ local P=\$1 DIR=\$IMG\$1 N NUMA=""
  N=\$(gpu_node \$(( 2*(P-8201) ))); [ -n "\$N" ] && [ "\$N" -ge 0 ] 2>/dev/null && NUMA="numactl --cpunodebind=\$N --preferred=\$N"
  \$NUMA unshare -m bash -c '
    mount -t tmpfs -o size=128G tmpfs /dev/shm || exit 97
    for f in "'"\$DIR"'"/shmfiles/psm_* "'"\$DIR"'"/shmfiles/link_remap.* "'"\$DIR"'"/shmfiles/sem.*; do
      [ -e "\$f" ] || continue; cp -a "\$f" "/dev/shm/\$(basename "\$f")"
    done
    chmod 600 /dev/shm/psm_* /dev/shm/link_remap.* /dev/shm/sem.* 2>/dev/null
    ionice -c1 -n0 nice -n -10 $CRIU_BIN restore -d --tcp-established --link-remap $RESTORE_ARGS --images-dir "'"\$DIR"'" 2> /var/log/criu-restore-boot-'"\$P"'.log'
  local rc=\$?; echo "criu restore \$P rc=\$rc \$(el)"; return \$rc
}
up_port(){ local P=\$1 DIR=\$IMG\$1 ORDER p a; ORDER=\$(cat "\$DIR/.order" 2>/dev/null)
  for p in \$ORDER; do
    [ -d /proc/\$p ] || { echo "\$P: pid \$p absent"; continue; }
    prlimit --pid "\$p" --memlock=unlimited:unlimited 2>/dev/null
    "\$CKPT" --get-state --pid "\$p" 2>/dev/null | grep -qi checkpointed || { echo "\$P: \$p not checkpointed (\$("\$CKPT" --get-state --pid \$p 2>&1))"; continue; }
    if [ -f "\$DIR/.toggle" ]; then
      for a in 1 2 3; do "\$CKPT" --toggle --pid "\$p" && { echo "\$P: resumed \$p (toggle) \$(el)"; break; }; echo "\$P: toggle \$p attempt \$a failed"; sleep 2; done
    else
      for a in 1 2 3; do "\$CKPT" --action restore --pid "\$p" && break; echo "\$P: restore \$p attempt \$a failed"; sleep 2; done
      "\$CKPT" --action unlock --pid "\$p" && echo "\$P: resumed \$p \$(el)"
    fi
  done
  if [ -f "\$DIR/.sleeping" ]; then
    for i in \$(seq 1 600); do [ -f /run/criu-prewarm.done ] && break; sleep 0.5; done
    echo "\$P: wake_up \$(el)"; curl -s --max-time 600 -X POST "http://127.0.0.1:\$P/wake_up" -o /dev/null
    echo "\$P: reload_weights start \$(el)"
    curl -s --max-time 1800 -X POST "http://127.0.0.1:\$P/collective_rpc" -H 'content-type: application/json' -d '{"method":"reload_weights"}' -o /dev/null
    echo "\$P: reload_weights done \$(el)"
  fi
  for i in \$(seq 1 600); do curl -sf -o /dev/null --max-time 2 http://127.0.0.1:\$P/health && { echo "\$P: health \$(el)"; break; }; sleep 1; done
  iptables -D INPUT -p tcp --dport \$P ! -i lo -j DROP 2>/dev/null && echo "\$P: port opened \$(el)"
}
nvidia-modprobe -u -c=0 2>/dev/null || modprobe nvidia-uvm 2>/dev/null || true
for i in \$(seq 1 90); do /usr/local/bin/cuinit-probe 2>/dev/null && { echo "cuda up \$(el)"; break; }; sleep 1; done
fabric_wait &
# pipelined: each port's CRIU restore is followed immediately by its own GPU restore (+ wake/reload) in the same background job
for P in \$PORTS; do
  [ -d \$IMG\$P ] || continue
  ( restore_one \$P && { for i in \$(seq 1 260); do [ -f /run/criu-fabric.done ] && break; sleep 0.5; done; up_port \$P; } ) &
done
wait
for P in \$PORTS; do iptables -D INPUT -p tcp --dport \$P ! -i lo -j DROP 2>/dev/null; done
echo "ports opened; READY \$(el)"
SCRIPT
sudo chmod +x "$UNIT_SCRIPT"
if [ "$INSTALL_UNIT" = 1 ]; then
sudo tee /etc/systemd/system/criu-autorestore.service >/dev/null <<UNIT
[Unit]
Description=Autonomous 4-port GPU-CRIU vLLM replay at boot (v9)
After=network-online.target nvidia-fabricmanager.service
Wants=network-online.target
[Service]
Type=oneshot
ExecStart=$UNIT_SCRIPT
RemainAfterExit=yes
[Install]
WantedBy=multi-user.target
UNIT
sudo systemctl daemon-reload && sudo systemctl enable criu-autorestore.service 2>&1 | tail -1
systemctl is-enabled criu-autorestore.service
fi
echo "--- read-back $UNIT_SCRIPT:"; grep -c . "$UNIT_SCRIPT"; grep -E '^echo "start|criu-hp. restore|PORTS=|IMG=' "$UNIT_SCRIPT" | head -4
echo INSTALL_DONE
